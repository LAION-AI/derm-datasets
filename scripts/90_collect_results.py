"""Collect all model results into report tables (Markdown) — report/results_tables.md.

Reads work/eval/*.json (copied back from donv). Missing experiments are shown as "–".
Accuracies in %, AUROC ×100.
"""
import json
import os

import numpy as np
import pandas as pd

from common import WORK

E = WORK / "eval"
OUT = WORK.parent / "report/results_tables.md"


def J(name):
    p = E / f"{name}.json"
    return json.load(open(p)) if p.exists() else {}


def v(d, k, scale=100, nd=1):
    x = d.get(k)
    if isinstance(x, dict):
        x = x.get("mean")
    return f"{scale * x:.{nd}f}" if isinstance(x, (int, float)) else "–"


def vs(n, k, scale=100, nd=1):
    """mean ± sd over seeds (n, n_s1, n_s2) if more than one run exists, else the single value."""
    xs = [J(x).get(k) for x in [n, n + "_s1", n + "_s2"]]
    xs = [x for x in xs if isinstance(x, (int, float))]
    if len(xs) > 1:
        import numpy as np
        return f"{scale * np.mean(xs):.{nd}f} ± {scale * np.std(xs, ddof=1):.{nd}f}"
    return f"{scale * xs[0]:.{nd}f}" if xs else "–"


def table(rows, cols):
    head = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    return head + "".join("| " + " | ".join(map(str, r)) + " |\n" for r in rows)


def main():
    md = ["# Results tables (generated by scripts/90_collect_results.py)\n"]
    # 1. CLIP / embedding models on the Derm1M protocol
    models = [("OpenAI CLIP ViT-B/16 (no fine-tuning)", "openai_vitb16"),
              ("+ fine-tuned on ours, 1k steps (3 seeds)", "clip_ft_ours"),
              ("+ fine-tuned on Derm1M, 1k steps (3 seeds)", "clip_ft_derm1m"),
              ("+ fine-tuned on ours, captions only (40.5k), 1k steps", "clip_ft_ours_caption_only"),
              ("+ fine-tuned on ours, 3k steps", "clip_ft_ours_3k"),
              ("+ fine-tuned on Derm1M, 3k steps", "clip_ft_derm1m_3k"),
              ("+ fine-tuned on ours ∪ Derm1M (139k pairs), 3k steps", "clip_ft_union_3k"),
              ("MedSigLIP-448", "medsiglip_448"), ("EmbeddingGemma-2", "embeddinggemma2")]
    rows = []
    for lab, n in models:
        rows.append([lab] + [vs(n, k) for k in ["zs_PAD_acc", "zs_HAM_acc", "zs_F17K_top1", "zs_Daffodil_acc", "zs_mean_acc",
                                                "lp_mean_acc", "ret_SkinCAP_i2t_R@10", "ret_SkinCAP_t2i_R@10"]])
    md.append("## Table 2 — Zero-shot, linear-probe and retrieval results (Derm1M benchmark protocol)\n")
    md.append(table(rows, ["Model", "ZS PAD", "ZS HAM", "ZS F17K top-1", "ZS Daffodil", "ZS mean", "LP mean",
                           "SkinCAP i→t R@10", "SkinCAP t→i R@10"]))
    # 2. per skin type (F17K zero-shot)
    rows = []
    for lab, n in models:
        rows.append([lab] + [vs(n, f"zs_F17K_acc_fst_{g}") for g in ["I-II", "III-IV", "V-VI"]])
    md.append("\n## Table 2a — Zero-shot AUROC (macro one-vs-rest ×100; threshold-free, less sensitive to class priors)\n")
    md.append(table([[lab] + [vs(n, f"zs_{b}_auroc") for b in ["PAD", "HAM", "Daffodil"]] for lab, n in models],
                    ["Model", "PAD", "HAM", "Daffodil"]))
    md.append("\n## Table 2b — Linear probe (test accuracy; standardised features, C chosen on val)\n")
    md.append(table([[lab] + [vs(n, f"lp_{b}_acc") for b in ["PAD", "HAM", "F17K", "Daffodil"]] + [vs(n, "lp_mean_acc")]
                     for lab, n in models], ["Model", "PAD", "HAM", "F17K", "Daffodil", "Mean"]))
    md.append("\n## Table 3 — Fitzpatrick17k zero-shot top-1 accuracy by skin-type group (expert labels; n = 1,461 / 1,099 / 407)\n")
    md.append(table(rows, ["Model", "FST I–II", "FST III–IV", "FST V–VI"]))
    # 3. adapters
    rows = []
    for lab, n in [("OpenAI CLIP ViT-B/16", "openai_vitb16"), ("MedSigLIP-448", "medsiglip_448"),
                   ("EmbeddingGemma-2", "embeddinggemma2")]:
        d = J(f"adapter_{n}")
        for cond in ["identity", "ours", "derm1m", "both"]:
            c = d.get(cond, {})
            rows.append([lab if cond == "identity" else "", cond, v(c, "zs_mean_acc"), v(c, "lp_mean_acc") if "lp_mean_acc" in c else "–",
                         v(c, "ret_i2t_R@10"), v(c, "ret_t2i_R@10")])
    md.append("\n## Table 4 — Frozen-backbone contrastive adapters trained on ours vs Derm1M (69.5k pairs each; mean of 3 seeds)\n")
    md.append(table(rows, ["Backbone", "Adapter trained on", "ZS mean", "LP mean", "SkinCAP i→t R@10", "SkinCAP t→i R@10"]))
    # 4. decision models zero-shot
    rows = []
    for lab, n in [("d1-3B (LiquidAI, 3B)", "d1-3B"), ("clef-flash (Cloudflare, 9B)", "clef-flash"),
                   ("clef (Cloudflare, 27B, 8-bit) — 300/bench", "clef27_300"),
                   ("clef-omni (Cloudflare, 30B-A3B) — 300/bench", "clefomni_300"),
                   ("h2o-lightning-4b (H2O.ai, 4B)", "h2o-lightning-4b"),
                   ("pplx-decider-v1.1 (Perplexity, 27B, bf16 + CPU offload) — 300/bench", "pplx-decider-27b_300")]:
        d = J(n)
        rows.append([lab, v(d, "zs_PAD_acc"), v(d, "zs_HAM_acc"), v(d, "zs_F17K_top1"), v(d, "zs_Daffodil_acc"), v(d, "zs_mean_acc")])
    md.append("\n## Table 5 — Decision models, zero-shot (same class names as the CLIP protocol)\n")
    rows.append(["Decision-1.0-Lux-9B (vllm-sr, 9B)", "n/a", "n/a", "n/a", "n/a", "text-only (no vision tower)"])
    md.append(table(rows, ["Model", "PAD", "HAM", "F17K top-1", "Daffodil", "Mean"]))
    sub = J("decision_subset300")   # written from the per-image probabilities (identical 300-image subsets)
    if sub:
        rows = []
        for lab, n in [("d1-3B", "d1-3B"), ("clef-flash", "clef-flash"), ("clef 27B (8-bit)", "clef27_300"),
                       ("clef-omni 30B-A3B", "clefomni_300"), ("h2o-lightning-4b", "h2o-lightning-4b"),
                       ("pplx-decider-v1.1 27B (bf16)", "pplx-decider-27b_300")]:
            if n not in sub:
                continue
            r = sub[n]
            rows.append([lab] + [f"{r[b][0]:.1f} / {r[b][1]:.1f}" for b in ["PAD", "HAM", "F17K", "Daffodil"]] +
                        [f"{sum(r[b][0] for b in r) / 4:.1f}"])
        md.append("\n## Table 5b — Decision models on identical subsets (300 random test images per benchmark, seed 0; "
                  "accuracy / balanced accuracy; 95% CI ≈ ±5–6 points)\n")
        md.append(table(rows, ["Model", "PAD", "HAM", "F17K top-1", "Daffodil", "Mean acc."]))
    # 5. supervised: CNN vs decision model vs linear probes (all on the LP test split of the benchmark package)
    rows = []
    for bench, cnn, d1 in [("PAD-UFES-20 (1,493 train)", "cnn_PAD", "d1ft_PAD"), ("HAM10000, 2k train", "cnn_HAM_2k", "d1ft_HAM_2k"),
                           ("HAM10000, full (8,012 train)", "cnn_HAM", None)]:
        c = J(cnn)
        f = J(d1) if d1 else {}
        sel, zs = f.get("selected", {}), f.get("zero_shot", {})
        key = "PAD" if "PAD" in bench else "HAM"
        lp = lambda n: f"{v(J(n), f'lp_{key}_acc')} / {v(J(n), f'lp_{key}_bal_acc')}"
        rows.append([bench, f"{v(c, 'test_acc')} / {v(c, 'test_bal_acc')}", f"{v(sel, 'test_acc')} / {v(sel, 'test_bal_acc')}",
                     f"{v(zs, 'test_acc')} / {v(zs, 'test_bal_acc')}", lp("openai_vitb16"), lp("clip_ft_ours"),
                     lp("clip_ft_derm1m"), lp("medsiglip_448")])
    md.append("\n## Table 6 — Supervised (accuracy / balanced accuracy, test split): EfficientNetV2-S vs d1-3B + LoRA vs "
              "linear probes on frozen embeddings (LP uses all training images)\n")
    md.append(table(rows, ["Task", "CNN", "d1-3B LoRA", "d1-3B zero-shot", "LP CLIP", "LP CLIP-ft ours (seed 0)",
                           "LP CLIP-ft Derm1M (seed 0)", "LP MedSigLIP"]))
    # 6. skin types vs population, diseases vs prevalence (72_skin_type_reference.py, 73_disease_prevalence.py)
    sk = WORK / "bias/skin_reference.json"
    if sk.exists():
        r = json.load(open(sk)); G = ["I–II", "III–IV", "V–VI"]
        pc = lambda d: [f"{100 * d[g]:.1f}" for g in G]
        rows = [["Ours, estimated"] + pc(r["ours"]["raw"]), ["Ours, bias-corrected"] + pc(r["ours"]["corrected"]),
                ["Derm1M, estimated"] + pc(r["derm1m"]["raw"]), ["Derm1M, bias-corrected"] + pc(r["derm1m"]["corrected"]),
                ["Fitzpatrick17k, expert"] + pc(r["f17k_expert"]["raw"]),
                ["Germany, SUN-Study 2012 (measured; V–VI incl. missing)"] + pc(r["germany_sun_2012"]),
                ["World, modelled (low-dark scenario)"] + pc(r["world_low_dark"]), ["World, modelled (high-dark scenario)"] + pc(r["world_high_dark"])]
        md.append("\n## Table 7 — Fitzpatrick skin-type groups (%): datasets (clinical photographs) vs population references\n")
        md.append(table(rows, ["", "I–II", "III–IV", "V–VI"]))
    dp = WORK / "bias/disease_prevalence.json"
    if dp.exists():
        r = json.load(open(dp))
        rows = [[c["condition"], f"{c['ref']:.1f}", f"{100 * c['share_prev']:.1f}", f"{c['img_ours']:,}", f"{c['ratio_ours']:.2f}",
                 c["class_ours"], f"{c['img_derm1m']:,}", f"{c['ratio_derm1m']:.2f}", c["class_derm1m"]]
                for c in sorted(r["conditions"], key=lambda c: -c["ratio_ours"])]
        md.append("\n## Table 8 — Disease representation vs GBD 2019 global prevalence (photographs, one per near-duplicate cluster)\n")
        md.append(table(rows, ["Condition", "Prevalence (M)", "Share of prevalence (%)", "Images ours", "Ratio ours", "Class ours",
                               "Images Derm1M", "Ratio Derm1M", "Class Derm1M"]))
        md.append("\nKeratinocyte carcinoma (vs GBD 2019 incidence; upper bounds): " + "; ".join(
            f"{k['condition']}: ours {k['ratio_ours_vs_incidence']:.0f}×, Derm1M {k['ratio_derm1m_vs_incidence']:.0f}×"
            for k in r["keratinocyte_carcinoma"]) + "\n")
    st = WORK / "eval/skin_tone_f17k.json"
    if st.exists():
        R = json.load(open(st))["models"]; G = ["I–II", "III–IV", "V–VI"]
        def agg(names, f, scale=100, nd=1):
            xs = [f(R[n]) for n in names if n in R]
            return "–" if not xs else f"{scale * np.mean(xs):.{nd}f}" + (f" ± {scale * np.std(xs, ddof=1):.{nd}f}" if len(xs) > 1 else "")
        rows = []
        for lab, names in [("OpenAI CLIP", ["openai_vitb16"]), ("CLIP ft ours, 1k (3 seeds)", ["clip_ft_ours", "clip_ft_ours_s1", "clip_ft_ours_s2"]),
                           ("CLIP ft Derm1M, 1k (3 seeds)", ["clip_ft_derm1m", "clip_ft_derm1m_s1", "clip_ft_derm1m_s2"]),
                           ("CLIP ft ours, 3k", ["clip_ft_ours_3k"]), ("CLIP ft Derm1M, 3k", ["clip_ft_derm1m_3k"]),
                           ("CLIP ft ours ∪ Derm1M, 3k", ["clip_ft_union_3k"]), ("MedSigLIP-448", ["medsiglip_448"]), ("EmbeddingGemma-2", ["embeddinggemma2"])]:
            rows.append([lab, agg(names, lambda m: m["skin_type"]["bal_acc"]), agg(names, lambda m: m["skin_type"]["recall_V–VI"])] +
                        [agg(names, lambda m, g=g: m["malignancy_auroc"][g], 1, 3) for g in G] +
                        [agg(names, lambda m, g=g: m["disease_acc"][g]) for g in G])
        md.append("\n## Table 10 — Fitzpatrick17k by expert skin type (linear probes, official split): skin-type recognition, "
                  "malignant vs benign AUROC and 114-disease accuracy per group\n")
        md.append(table(rows, ["Model", "Skin type bal. acc", "V–VI recall", "Malig. AUROC I–II", "III–IV", "V–VI",
                               "Disease acc I–II", "III–IV", "V–VI"]))
    sx = WORK / "bias/sex_distribution.json"
    if sx.exists():
        r = json.load(open(sx))
        f = lambda d: f"{100 * d['female_share']:.1f} ({d['n']:,})" if d["n"] else "–"
        rows = [["All photographs", f"{100 * r['world_female_share']:.1f} (world)", f(r["ours"]["with_sex"]), "", f(r["derm1m"]["with_sex"]), ""]]
        for c in r["conditions"]:
            rows.append([c["condition"], f"{100 * c['gbd_female_share']:.1f}", f(c["ours"]), c["ours"].get("class", "n < 10"),
                         f(c["derm1m"]), c["derm1m"].get("class", "n < 10")])
        md.append("\n## Table 9 — Patient sex: female share % (n photographs with known sex) vs GBD 2019 female share of prevalence\n")
        md.append(table(rows, ["Condition", "Reference", "Ours", "Ours vs ref.", "Derm1M", "Derm1M vs ref."]))
    OUT.write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
